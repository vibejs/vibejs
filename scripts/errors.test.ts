import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { docsBase, errorsGen, main, parseMessages } from './errors.ts';

const DI = `# Dependency injection

## VIBE9101: Missing provider
> No provider for {token} in module {module}.

Prose for the docs only.

### Fix
- Add {token} to providers.
- Import a module that exports {token}.

### Example
\`\`\`md
## Not a heading
### Not a section
\`\`\`

## VIBE9102: Old error (retired)
> The old thing failed.

### Fix
- Do the new thing.
`;

const BASE: Record<string, string> = {
  'packages/errors/package.json': '{ "version": "0.3.1" }',
  'packages/server/package.json': '{ "dependencies": { "@vibejs-org/errors": "workspace:*" } }',
  'packages/server/messages/di.md': DI,
  'packages/server/src/inject.ts': "throw vibeError('VIBE9101', { token, module });",
  'packages/server/src/inject.test.ts': "expect(error).toMatchObject({ code: 'VIBE9101' });",
  'packages/create-vibejs/package.json': '{ "bin": { "create-vibejs": "./bin.js" } }',
  'packages/create-vibejs/messages/create.md':
    '## VIBE8101: Bad name\n> The name {name} is invalid.\n\n### Fix\n- Pick another name.\n',
  'packages/create-vibejs/bin.js': "fail('VIBE8101');",
  'packages/create-vibejs/bin.test.ts': "expect(run()).toMatchObject({ code: 'VIBE8101' });",
  'packages/ui/package.json': '{}',
};

let root: string;
let errors: string[];

function put(files: Record<string, string>): void {
  for (const [file, text] of Object.entries(files)) {
    mkdirSync(dirname(join(root, file)), { recursive: true });
    writeFileSync(join(root, file), text);
  }
}
const get = (file: string): string => readFileSync(join(root, file), 'utf8');
const run = (...argv: string[]): number => main(root, argv);
function check(): string[] {
  errors = [];
  run('--check');
  return errors;
}

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), 'vibejs-errors-'));
  put(BASE);
  errors = [];
  vi.spyOn(console, 'error').mockImplementation((line: string) => errors.push(line));
  vi.spyOn(console, 'log').mockImplementation(() => {});
});
afterEach(() => {
  rmSync(root, { recursive: true, force: true });
  vi.restoreAllMocks();
});

describe('docsBase', () => {
  it('follows the major version', () => {
    expect(docsBase('0.3.1')).toBe('https://vibejs.org/v0/errors/');
    expect(docsBase('1.2.3')).toBe('https://vibejs.org/v1/errors/');
  });
});

describe('parseMessages', () => {
  it('parses entries, ignoring headings in code fences', () => {
    const { entries, problems } = parseMessages('server', 'di.md', DI);
    expect(problems).toEqual([]);
    expect(entries).toEqual([
      {
        code: 'VIBE9101',
        package: 'server',
        title: 'Missing provider',
        message: 'No provider for {token} in module {module}.',
        fixes: ['Add {token} to providers.', 'Import a module that exports {token}.'],
        body: 'Prose for the docs only.\n\n### Example\n```md\n## Not a heading\n### Not a section\n```',
        retired: false,
        source: expect.stringMatching(/^> No provider[^]*### Fix[^]*### Not a section\n```$/),
      },
      {
        code: 'VIBE9102',
        package: 'server',
        title: 'Old error',
        message: 'The old thing failed.',
        fixes: ['Do the new thing.'],
        body: '',
        retired: true,
        source: '> The old thing failed.\n\n### Fix\n- Do the new thing.',
      },
    ]);
  });
});

const golden = (
  load: string,
) => `// GENERATED by scripts/errors.ts from ../messages/*.md. Do not edit.
import { defineErrors, type VibeErrorFactory } from '@vibejs-org/errors';

const MESSAGES = {
  VIBE9101: ["No provider for {token} in module {module}.","Add {token} to providers.","Import a module that exports {token}."],
} as const;

export const vibeError: VibeErrorFactory<typeof MESSAGES> = defineErrors(${load});
`;

describe('errorsGen', () => {
  const entries = parseMessages('x', 'di.md', DI).entries;

  it('loads the table only under __DEV__ for packages/ui', () => {
    expect(errorsGen('ui', entries)).toBe(golden('() => (__DEV__ ? MESSAGES : undefined)'));
  });

  it('always loads the table elsewhere and drops retired entries', () => {
    expect(errorsGen('server', entries)).toBe(golden('() => MESSAGES'));
  });
});

describe('pnpm errors', () => {
  it('writes the generated files', () => {
    expect(run()).toBe(0);
    expect(get('packages/errors/src/docs-base.gen.ts')).toBe(
      "// GENERATED by scripts/errors.ts from the package version. Do not edit.\nexport const DOCS_BASE: string = 'https://vibejs.org/v0/errors/';\n",
    );
    expect(get('packages/server/src/errors.gen.ts')).toBe(
      errorsGen('server', parseMessages('server', 'di.md', DI).entries),
    );
    // create-vibejs has no @vibejs-org/errors dependency, ui has no messages.
    expect(existsSync(join(root, 'packages/create-vibejs/src/errors.gen.ts'))).toBe(false);
    expect(existsSync(join(root, 'packages/ui/src/errors.gen.ts'))).toBe(false);
    const catalog = get('packages/cli/src/catalog.gen.ts');
    expect(catalog).toContain('export const CATALOG: readonly CatalogEntry[] = [');
    const json = JSON.parse(catalog.slice(catalog.indexOf('= [') + 2, catalog.lastIndexOf(';')));
    expect(json.map((entry: { code: string }) => entry.code)).toEqual([
      'VIBE8101',
      'VIBE9101',
      'VIBE9102',
    ]);
    expect(json[2]).toEqual({
      code: 'VIBE9102',
      package: 'server',
      title: 'Old error',
      message: 'The old thing failed.',
      fixes: ['Do the new thing.'],
      body: '',
      docs: 'https://vibejs.org/v0/errors/VIBE9102',
      retired: true,
    });
  });

  it('writes errors.gen.ts for a package that bundles @vibejs-org/errors as a devDependency', () => {
    put({
      'packages/vscode/package.json':
        '{ "devDependencies": { "@vibejs-org/errors": "workspace:*" } }',
      'packages/vscode/messages/extension.md':
        '## VIBE6101: Missing\n> Install {extension}.\n\n### Fix\n- Install it.\n',
    });
    expect(run()).toBe(0);
    expect(get('packages/vscode/src/errors.gen.ts')).toContain('VIBE6101: ["Install {extension}."');
  });

  it('regenerates DOCS_BASE after a major bump', () => {
    put({ 'packages/errors/package.json': '{ "version": "1.0.0" }' });
    expect(run()).toBe(0);
    expect(get('packages/errors/src/docs-base.gen.ts')).toContain(
      "'https://vibejs.org/v1/errors/'",
    );
    expect(get('packages/cli/src/catalog.gen.ts')).toContain(
      '"https://vibejs.org/v1/errors/VIBE9101"',
    );
  });

  it('removes an errors.gen.ts that is no longer needed', () => {
    put({ 'packages/ui/src/errors.gen.ts': 'old' });
    expect(run()).toBe(0);
    expect(existsSync(join(root, 'packages/ui/src/errors.gen.ts'))).toBe(false);
  });

  it('writes nothing when the catalog is invalid', () => {
    put({
      'packages/server/messages/bad.md':
        '## VIBE0001: Wrong range\n> Message.\n\n### Fix\n- Fix.\n',
    });
    expect(run()).toBe(1);
    expect(errors).toEqual([
      'VIBE0001 is outside the ranges of packages/server (see CONTRACTS.md C2)',
    ]);
    expect(existsSync(join(root, 'packages/server/src/errors.gen.ts'))).toBe(false);
  });

  it('writes one docs page per code with --docs, retired codes included', () => {
    expect(run('--docs', join(root, 'site'))).toBe(0);
    expect(get('site/VIBE9102.md')).toBe(`---
code: VIBE9102
title: "Old error"
package: server
retired: true
---

# VIBE9102: Old error

> The old thing failed.

### Fix
- Do the new thing.
`);
    expect(get('site/VIBE9101.md')).toContain(
      'retired: false\n---\n\n# VIBE9101: Missing provider\n\n> No provider',
    );
    expect(get('site/VIBE8101.md')).toContain('package: create-vibejs');
  });

  it('writes exactly one page per catalog code plus index.md with --docs', () => {
    expect(run('--docs', join(root, 'site'))).toBe(0);
    expect(readdirSync(join(root, 'site')).toSorted()).toEqual([
      'VIBE8101.md',
      'VIBE9101.md',
      'VIBE9102.md',
      'index.md',
    ]);
    expect(get('site/index.md')).toBe(`# Error codes

| Code | Title | Package | Status |
| --- | --- | --- | --- |
| [VIBE8101](./VIBE8101.md) | Bad name | create-vibejs |  |
| [VIBE9101](./VIBE9101.md) | Missing provider | server |  |
| [VIBE9102](./VIBE9102.md) | Old error | server | retired |
`);
  });

  it('rejects unknown arguments', () => {
    expect(run('--nope')).toBe(2);
    expect(errors[0]).toContain('Usage: node scripts/errors.ts [--check] [--docs <dir>]');
  });
});

describe('pnpm errors --check', () => {
  beforeEach(() => {
    run();
  });

  it('passes on a valid, fresh, thrown and tested catalog, and rewrites only the CLI catalog', () => {
    const generated = get('packages/server/src/errors.gen.ts');
    rmSync(join(root, 'packages/cli/src/catalog.gen.ts'));
    expect(run('--check')).toBe(0);
    expect(errors).toEqual([]);
    expect(get('packages/server/src/errors.gen.ts')).toBe(generated);
    expect(get('packages/cli/src/catalog.gen.ts')).toContain('VIBE9101');
  });

  // Rule 1
  it.each([
    ['## VIBE91: Short', 'the heading must be "## VIBE####: Title"'],
    ['## VIBE9103: No message\n\n### Fix\n- Fix.', 'exactly one "> message" line'],
    ['## VIBE9103: Two\n> One.\n> Two.\n\n### Fix\n- Fix.', 'exactly one "> message" line'],
    ['## VIBE9103: Late\nProse.\n> Message.\n\n### Fix\n- Fix.', 'exactly one "> message" line'],
    ['## VIBE9103: No fix\n> Message.', '"### Fix" must hold one or more "- " bullets'],
    ['## VIBE9103: Prose fix\n> Message.\n\n### Fix\nJust do it.', '"### Fix" must hold'],
    [
      '## VIBE9103: Odd\n> Message.\n\n### Fix\n- Fix.\n\n### Notes\nx',
      'unexpected section "### Notes"',
    ],
    ['## VIBE9103: Twice\n> Message.\n\n### Fix\n- A.\n\n### Fix\n- B.', 'a section appears twice'],
    [
      '## VIBE9103: Case\n> No {Token}.\n\n### Fix\n- Fix.',
      'malformed placeholder in "No {Token}."',
    ],
    [
      '## VIBE9103: Open\n> Message.\n\n### Fix\n- Add {token.',
      'malformed placeholder in "Add {token."',
    ],
  ])('fails on a format error: %j', (entry, problem) => {
    put({ 'packages/server/messages/zz.md': `${entry}\n` });
    expect(check().join('\n')).toContain(problem);
  });

  // Rule 2
  it('fails on a code outside its package range', () => {
    put({
      'packages/server/messages/zz.md': '## VIBE9900: Reserved\n> Message.\n\n### Fix\n- Fix.\n',
      'packages/unknown/messages/zz.md': '## VIBE0500: Unlisted\n> Message.\n\n### Fix\n- Fix.\n',
      'packages/unknown/package.json': '{}',
    });
    expect(check()).toEqual(
      expect.arrayContaining([
        'VIBE0500 is outside the ranges of packages/unknown (see CONTRACTS.md C2)',
        'VIBE9900 is outside the ranges of packages/server (see CONTRACTS.md C2)',
      ]),
    );
  });

  it('fails on a code duplicated repo-wide, retired codes included', () => {
    put({ 'packages/ui/messages/zz.md': '## VIBE9102: Copy\n> Message.\n\n### Fix\n- Fix.\n' });
    expect(check()).toContain('VIBE9102 is defined in packages/server and packages/ui');
  });

  // Rule 3
  it.each(['packages/server/src/errors.gen.ts', 'packages/errors/src/docs-base.gen.ts'])(
    'fails on a stale %s',
    (file) => {
      put({ [file]: `${get(file)}// edited\n` });
      expect(check()).toEqual([`${join(file)} is stale; run pnpm errors`]);
    },
  );

  it('fails on an errors.gen.ts that should not exist, and on a missing one', () => {
    put({ 'packages/ui/src/errors.gen.ts': 'old' });
    rmSync(join(root, 'packages/server/src/errors.gen.ts'));
    expect(check()).toEqual([
      join('packages/server/src/errors.gen.ts') + ' is stale; run pnpm errors',
      join('packages/ui/src/errors.gen.ts') + ' is stale; run pnpm errors',
    ]);
  });

  // Rule 4
  it('fails on a live code without a literal in a non-test source', () => {
    put({
      'packages/server/src/inject.ts': '// VIBE9101 is mentioned, but not thrown',
      'packages/server/src/inject.test-d.ts': "vibeError('VIBE9101');",
    });
    expect(check()).toEqual([
      "VIBE9101 is never thrown: no 'VIBE9101' in a non-test source of packages/server",
    ]);
  });

  it('fails on a live code without a literal in a test', () => {
    put({ 'packages/server/src/inject.test.ts': '' });
    expect(check()).toEqual([
      "VIBE9101 is never asserted: no 'VIBE9101' in a *.test.ts or *.suite.ts of packages/server",
    ]);
  });

  it('accepts a literal in a shared suite', () => {
    put({
      'packages/server/src/inject.test.ts': '',
      'packages/server/test/inject.suite.ts': "isVibeError(error, 'VIBE9101');",
    });
    expect(check()).toEqual([]);
  });

  it('scans the bin of a package without src', () => {
    put({ 'packages/create-vibejs/bin.js': '' });
    expect(check()).toEqual([
      "VIBE8101 is never thrown: no 'VIBE8101' in a non-test source of packages/create-vibejs",
    ]);
  });

  it('finds nothing in a package without src and bin', () => {
    put({ 'packages/create-vibejs/package.json': '{}' });
    expect(check()).toContain(
      "VIBE8101 is never thrown: no 'VIBE8101' in a non-test source of packages/create-vibejs",
    );
  });
});

describe('as a script', () => {
  const argv = process.argv;
  afterEach(() => {
    process.argv = argv;
    process.exitCode = undefined;
  });

  it('runs main on the repo and sets the exit code', async () => {
    process.argv = ['node', fileURLToPath(new URL('errors.ts', import.meta.url)), '--nope'];
    vi.resetModules();
    await import('./errors.ts');
    expect(process.exitCode).toBe(2);
  });
});
