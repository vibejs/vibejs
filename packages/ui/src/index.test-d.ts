expectTypeOf<Exported>().not.toBeAny();

// CSSProperties is the csstype object form of a style value, with custom properties.
expectTypeOf<CSSProperties>().toExtend<StyleValue>();
expectTypeOf<{ color: 'red'; '--gap': 2 }>().toExtend<CSSProperties>();
// @ts-expect-error an unknown CSS property
const style: CSSProperties = { colour: 'red' };
expectTypeOf(style).toEqualTypeOf<CSSProperties>();
